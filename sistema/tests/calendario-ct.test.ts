    const sexta=await atender("sexta-feira",{acao:"consultar",modalidade:"Muay Thai",idade:25});
    assert.match(sexta!,/sexta-feira, 20\/11\/2026/);assert.match(sexta!,/Não encontrei uma aula compatível/);
